function assert(condition: boolean, testName: string, details?: any) {
  if (!condition) {
    console.error(`❌ FAILED: ${testName}`, details || '');
    throw new Error(`Test assertion failed: ${testName}`);
  } else {
    console.log(`✅ PASSED: ${testName}`);
  }
}

